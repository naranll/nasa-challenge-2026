"""Validate the task list, write docs/ISSUES.md, and (only on request) create the GitHub issues.

    python scripts/issues/create_issues.py            # dry run: validate + regenerate docs/ISSUES.md
    python scripts/issues/create_issues.py --publish  # create the issues with the gh CLI

--publish needs the GitHub CLI (`gh auth login` done). It checks the target repo, skips tasks whose
"[ID]" title already exists, and creates issues in dependency order so "Blocked by: #n" is correct.
"""
import json
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from tasks import LANES, TASKS  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
BY_ID = {t["id"]: t for t in TASKS}


def validate():
    errors = []
    if len(BY_ID) != len(TASKS):
        errors.append("duplicate task ids")
    for t in TASKS:
        if t["lane"] not in LANES:
            errors.append(f"{t['id']}: unknown lane {t['lane']}")
        for b in t["blocked_by"]:
            if b not in BY_ID:
                errors.append(f"{t['id']}: blocked_by unknown {b}")
            elif BY_ID[b]["wave"] > t["wave"]:
                errors.append(f"{t['id']} (wave {t['wave']}) is blocked by later-wave {b} (wave {BY_ID[b]['wave']})")
        if not t["done"]:
            errors.append(f"{t['id']}: needs at least one 'done' criterion")
    # cycle check
    state = {}

    def visit(i, path):
        if state.get(i) == 2:
            return
        if state.get(i) == 1:
            errors.append("cycle: " + " -> ".join(path + [i]))
            return
        state[i] = 1
        for b in BY_ID.get(i, {}).get("blocked_by", []):
            visit(b, path + [i])
        state[i] = 2

    for t in TASKS:
        visit(t["id"], [])
    return errors


def order():
    """Topological order: blockers first."""
    done, out = set(), []

    def add(i):
        if i in done:
            return
        done.add(i)
        for b in BY_ID[i]["blocked_by"]:
            add(b)
        out.append(i)

    for t in TASKS:
        add(t["id"])
    return out


def title(t):
    return f"[{t['id']}] {t['title']}"


def labels(t):
    ls = [f"lane:{t['lane'].lower()}", f"wave:{t['wave']}"]
    if t["gate"]:
        ls.append(f"gate:{t['gate']}")
    ls += [{"lean": "lean-mvp", "ml": "forecast"}[x] for x in t["tags"]]
    return ls


def body(t, numbers=None):
    numbers = numbers or {}
    blockers = ", ".join(f"#{numbers[b]} ({b})" if b in numbers else b for b in t["blocked_by"])
    lines = []
    if t["blocked_by"]:
        lines += [f"Blocked by: {blockers}", ""]
    lines += [
        f"**Lane:** {t['lane']} {LANES[t['lane']]} · **Wave:** {t['wave']} · **Time-box:** {t['box']}"
        + (f" · **Gate:** {t['gate']}" if t["gate"] else ""),
        f"**Can start from:** {t['start_with']}" + ("" if t["blocked_by"] else " (nothing blocks this)"),
        "",
        "## What",
        t["summary"],
        "",
        "## Done when",
        *[f"- [ ] {d}" for d in t["done"]],
        "",
        "## You may edit",
        t["edits"] + "  \n(everything else is read-only for this ticket, see TASKS.md §1)",
        "",
        "## Rules",
        "- Numbers shown to users come from a script and go in `docs/claims.md`. Never invent data, numbers, citations or status.",
        "- Build against `contracts/` and `fixtures/`. Synthetic data never reaches the demo.",
        "- Time-box is hard: at 100% ship what exists, post status, move on.",
        "- PR description ends with `AI-used: <tool> — <what for> — <reviewed by>` and says `Closes #<this issue>`.",
        "",
        f"_Source: {t['ref']}_",
    ]
    return "\n".join(lines)


def write_index():
    ready = [t for t in TASKS if not t["blocked_by"]]
    lines = [
        "# Issue plan (generated)",
        "",
        "Generated by `python scripts/issues/create_issues.py` from `scripts/issues/tasks.py`. Edit the source, not this file.",
        "",
        f"**{len(TASKS)} tickets · {len(ready)} can start right now (nothing blocks them).** "
        "`lean` = in the lean MVP · `ml` = headline forecast product (PLAN D15).",
        "",
    ]
    for wave, name in ((0, "Wave 0 — start now (gate G0)"), (1, "Wave 1 — parallel, build on fixtures"),
                       (2, "Wave 2 — needs real output from another ticket")):
        lines += [f"## {name}", "", "| ID | Ticket | Lane | Box | Can start from | Blocked by | Gate | Tags |", "|---|---|---|---|---|---|---|---|"]
        for t in TASKS:
            if t["wave"] == wave:
                lines.append(f"| {t['id']} | {t['title']} | {t['lane']} | {t['box']} | {t['start_with']} | "
                             f"{', '.join(t['blocked_by']) or '—'} | {t['gate'] or ''} | {', '.join(t['tags'])} |")
        lines.append("")
    lines += ["## Per lane", ""]
    for lane, name in LANES.items():
        mine = [t for t in TASKS if t["lane"] == lane]
        hours = sum(float(t["box"].split()[0]) * (1 if "h" in t["box"] else 1 / 60) for t in mine if t["box"][0].isdigit())
        lines.append(f"- **{lane} {name}:** {len(mine)} tickets, about {hours:.1f} h of boxed work")
    (ROOT / "docs" / "ISSUES.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def gh(*args, check=True, stdin=None):
    return subprocess.run(["gh", *args], capture_output=True, text=True, encoding="utf-8", input=stdin,
                          check=check, cwd=ROOT)


def publish():
    try:
        repo = json.loads(gh("repo", "view", "--json", "nameWithOwner").stdout)["nameWithOwner"]
    except (FileNotFoundError, subprocess.CalledProcessError):
        sys.exit("The GitHub CLI (gh) is missing or not logged in. Install it and run `gh auth login`.")
    print(f"Target repo: {repo}")
    if input("Create issues in this repo? [y/N] ").strip().lower() != "y":
        sys.exit("Aborted.")

    all_labels = {l for t in TASKS for l in labels(t)}
    for l in sorted(all_labels):
        gh("label", "create", l, "--force", check=False)

    existing = {i["title"]: i["number"] for i in json.loads(gh("issue", "list", "--state", "all", "--limit", "500",
                                                              "--json", "number,title").stdout)}
    numbers = {}
    for i in order():
        t = BY_ID[i]
        if title(t) in existing:
            numbers[i] = existing[title(t)]
            print(f"skip   {title(t)} (exists as #{numbers[i]})")
            continue
        out = gh("issue", "create", "--title", title(t), "--body-file", "-",
                 *sum((["--label", l] for l in labels(t)), []), stdin=body(t, numbers)).stdout.strip()
        numbers[i] = int(out.rsplit("/", 1)[-1])
        print(f"create #{numbers[i]}  {title(t)}")


if __name__ == "__main__":
    errs = validate()
    if errs:
        sys.exit("Invalid task list:\n  " + "\n  ".join(errs))
    write_index()
    ready = [t["id"] for t in TASKS if not t["blocked_by"]]
    print(f"OK: {len(TASKS)} tickets, {len(ready)} startable now -> docs/ISSUES.md")
    if "--publish" in sys.argv:
        publish()
